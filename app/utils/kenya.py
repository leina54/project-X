def canonical_county(value: str) -> str:
    key = " ".join(value.lower().replace("-", " ").replace(" county", "").split())
    try:
        return KENYAN_COUNTIES[key]
    except KeyError as exc:
        raise ValueError("County must be one of Kenya's 47 counties") from exc
